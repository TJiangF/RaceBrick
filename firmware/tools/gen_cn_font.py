#!/usr/bin/env python3
"""Generate the compact Chinese glyph atlas used by gfx_text_i18n().

Source fonts are NOT committed:
  1. Noto Sans CJK SC Black (SIL OFL)
  2. Fusion Pixel 12px proportional zh-Hans (SIL OFL)

Only the GB2312 level-1 common Hanzi (3755) plus common Chinese punctuation
are included, keeping the atlas near 3500 characters instead of the full
GB2312 set. Every glyph is thresholded to 1bpp so strokes are solid on the
LCD, and the atlas is much smaller than the old 2bpp version.

Output: src/font_cn_data.h
"""
import argparse
import os
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_NOTO = "/tmp/rb_fonts/NotoSansCJKsc-Black.otf"
DEFAULT_PIXEL = "/tmp/rb_fonts/fusion/fusion-pixel-12px-proportional-zh_hans.otf"

# Common Chinese punctuation and symbols used by music metadata/lyrics.
CN_PUNCT = "，。！？；：、（）【】《》“”‘’…—～·「」『』〈〉〔〕〖〗·×÷±°％＋－＝"
def cps_common():
    out = {ord(c) for c in CN_PUNCT}
    # GB2312 level-1 rows B0-D7 contain the 3755 most common Hanzi.
    for a in range(0xB0, 0xD8):
        for b in range(0xA1, 0xFF):
            try:
                ch = bytes((a, b)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1:
                out.add(ord(ch))
    return sorted(out)

def raster(font, ch, box):
    im = Image.new("L", (box, box), 0)
    d = ImageDraw.Draw(im)
    bb = font.getbbox(ch)
    if bb:
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        x = (box - w) // 2 - bb[0]
        y = (box - h) // 2 - bb[1]
        d.text((x, y), ch, font=font, fill=255)
    data = bytearray((box * box + 7) // 8)
    for i in range(box * box):
        x, y = i % box, i // box
        if im.getpixel((x, y)) >= 128:
            data[i >> 3] |= 1 << (7 - (i & 7))
    return bytes(data)

def main():
    ap = argparse.ArgumentParser(description="Generate src/font_cn_data.h")
    ap.add_argument("--noto", default=os.environ.get("NOTO_FONT", DEFAULT_NOTO))
    ap.add_argument("--pixel", default=os.environ.get("PIXEL_FONT", DEFAULT_PIXEL))
    ap.add_argument("--out", default=str(ROOT / "src/font_cn_data.h"))
    args = ap.parse_args()
    noto_path, pixel_path, out = Path(args.noto), Path(args.pixel), Path(args.out)
    for path in (noto_path, pixel_path):
        if not path.exists():
            raise SystemExit("font not found: %s (override with --noto/--pixel)" % path)

    cps = cps_common()
    n = len(cps)
    noto16 = ImageFont.truetype(str(noto_path), 16)
    noto12 = ImageFont.truetype(str(noto_path), 12)
    pix12 = ImageFont.truetype(str(pixel_path), 12)
    pix16 = ImageFont.truetype(str(pixel_path), 16)
    a16 = [raster(noto16, chr(c), 16) for c in cps]
    a12 = [raster(noto12, chr(c), 12) for c in cps]
    p12 = [raster(pix12, chr(c), 12) for c in cps]
    p16 = [raster(pix16, chr(c), 16) for c in cps]
    with out.open("w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_cn_font.py - do not hand-edit. */\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write("#define CN_GLYPH_COUNT %d\n" % n)
        f.write("#define CN16_BYTES %d\n#define CN12_BYTES %d\n#define CNPIX_BYTES %d\n" %
                (len(a16[0]), len(a12[0]), len(p12[0])))
        f.write("static const uint32_t CN_CODEPOINTS[CN_GLYPH_COUNT] = {\n")
        f.write(",".join("0x%X" % c for c in cps)); f.write("\n};\n")
        for name, arr in [("CN_NOTO16", a16), ("CN_NOTO12", a12),
                          ("CN_FUSION12", p12), ("CN_FUSION16", p16)]:
            f.write("static const uint8_t %s[CN_GLYPH_COUNT][%d] = {\n" % (name, len(arr[0])))
            for row in arr:
                f.write("{" + ",".join("%d" % b for b in row) + "},\n")
            f.write("};\n")
    total = n * (len(a16[0]) + len(a12[0]) + len(p12[0]) + len(p16[0]))
    print("generated", out, "glyphs", n, "binary bytes", total)

if __name__ == "__main__":
    main()
