void theme_set(int light) {
    s_light = light ? 1 : 0;
    if (s_style) PAL = s_light ? F1_LIGHT : F1_DARK;
    else PAL = s_light ? LIGHT : DARK;
}
int theme_is_light(void) { return s_light; }
void theme_set_style(int f1) {
    s_style = f1 ? 1 : 0;
    theme_set(s_light);
}
int theme_style(void) { return s_style; }
